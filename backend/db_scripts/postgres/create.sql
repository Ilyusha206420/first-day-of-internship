CREATE TABLE users (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    name TEXT NOT NULL,
    pass TEXT NOT NULL
);

CREATE TABLE tokens (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    refresh_token TEXT NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE contents (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    data TEXT UNIQUE NOT NULL
);

CREATE TABLE methods (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    method_name TEXT UNIQUE NOT NULL
);

CREATE TABLE nodes (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    method_id BIGINT REFERENCES methods (id) ON UPDATE CASCADE,
    content_id BIGINT REFERENCES contents (id)
);

CREATE TABLE edges (
    src_id BIGINT NOT NULL REFERENCES nodes (id),
    tgt_id BIGINT NOT NULL REFERENCES nodes (id),
    PRIMARY KEY (src_id, tgt_id)
);

CREATE TABLE IF NOT EXISTS dialogs (
    dialog_id BIGINT NOT NULL,
    dialog_step BIGINT NOT NULL,
    started_at TIMESTAMP NOT NULL DEFAULT NOW(),
    ended_at TIMESTAMP,
    user_id BIGINT NOT NULL REFERENCES users (id),
    content_id BIGINT NOT NULL REFERENCES contents (id),

    PRIMARY KEY (dialog_id, dialog_step)
);